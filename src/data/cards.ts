// Automatically calibrate all pack items so the maximum payout depending on pack price is strictly 4X
PACKS.forEach((pack) => {
  const targetMaxPayout = Number((pack.price * 4).toFixed(2));
  const minTarget = Number(Math.max(0.10, pack.price * 0.1).toFixed(2));

  const sorted = [...pack.items].sort((a, b) => a.value - b.value);
  const minCardVal = sorted[0]?.value || 1;
  const maxCardVal = sorted[sorted.length - 1]?.value || 1;

  pack.items = pack.items.map((card) => {
    if (card.value === maxCardVal) {
      return {
        ...card,
        rarity: 'Grail',
        value: targetMaxPayout,
        usdValue: targetMaxPayout
      };
    }
    const ratio = maxCardVal > minCardVal ? (card.value - minCardVal) / (maxCardVal - minCardVal) : 0;
    const scaledVal = Number((minTarget + ratio * (targetMaxPayout * 0.7 - minTarget)).toFixed(2));

    // Distribute proper rarity tiers across the pack items
    let rarity = card.rarity;
    if (card.value === minCardVal) {
      rarity = 'Common';
    } else if (ratio < 0.25) {
      rarity = 'Uncommon';
    } else if (ratio < 0.50) {
      rarity = 'Rare';
    } else if (ratio < 0.80) {
      rarity = 'Ultra Rare';
    } else {
      rarity = 'Secret Rare';
    }

    return {
      ...card,
      rarity,
      value: scaledVal,
      usdValue: scaledVal
    };
  });
});

